// Resolves the best-known contact URL for an office: the verified override if
// we have one, otherwise a guessed `${url}/contact` (works for most offices).
export function resolveContactUrl(officeUrl) {
  if (!officeUrl) return null;
  let hostname;
  try {
    hostname = new URL(officeUrl).hostname;
  } catch {
    return officeUrl;
  }
  return CONTACT_OVERRIDES[hostname] || `${officeUrl.replace(/\/$/, "")}/contact`;
}
